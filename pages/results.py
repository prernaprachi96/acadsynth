def render():
    st.markdown("""
    <div class='page-title'>Results</div>
    <div class='page-subtitle'>All documents generated by the pipeline, newest first.</div>
    """, unsafe_allow_html=True)

    # ── Filter bar ────────────────────────────────────────────────────────────
    col_s, col_f = st.columns([3, 1])
    with col_s:
        search = st.text_input("Search", placeholder="Filter by keyword…",
                               label_visibility="collapsed")
    with col_f:
        fmt_filter = st.selectbox("Format", ["All formats", ".docx", ".pptx", ".md"],
                                  label_visibility="collapsed")

    filtered = RESULTS
    if search.strip():
        filtered = [r for r in filtered if search.lower() in r["query"].lower()]
    if fmt_filter != "All formats":
        filtered = [r for r in filtered if r["format"] == fmt_filter]

    st.markdown("<div style='height:8px'></div>", unsafe_allow_html=True)

    if not filtered:
        st.markdown("""
        <div class='paper-card' style='text-align:center; color:#8C6A4F;
             font-size:0.9rem; padding:2rem'>
            No results match your search.
        </div>
        """, unsafe_allow_html=True)
        return

    for r in filtered:
        with st.expander(f"{r['query']}  ·  {r['format']}  ·  {r['date']}"):
            st.markdown(f"""
            <div style='display:flex; gap:6px; flex-wrap:wrap; margin-bottom:1rem'>
                <span class='tag tag-orange'>{r['format']}</span>
                <span class='tag tag-gray'>{r['depth']}</span>
                <span class='tag tag-gray'>{r['style']}</span>
                <span class='tag tag-blue'>{r['sources']} sources</span>
                <span class='tag tag-gray'>~{r['words']} words</span>
            </div>
            """, unsafe_allow_html=True)

            st.markdown(f"<div class='result-box'>{r['preview']}</div>",
                        unsafe_allow_html=True)

            st.markdown("<div style='height:10px'></div>", unsafe_allow_html=True)
            dl_col, del_col, _ = st.columns([1, 1, 5])
            with dl_col:
                st.download_button(
                    f"Download {r['format']}",
                    data=r["preview"].encode(),
                    file_name=f"result_{r['id']}.txt",
                    mime="text/plain",
                    key=f"dl_{r['id']}",
                )
            with del_col:
                if st.button("Delete", key=f"del_{r['id']}"):
                    st.warning("Connect this to your database to delete.")
